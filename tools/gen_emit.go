func docOut(inv []invEntry, cov map[string][]how) string {
	var b strings.Builder
	counts := map[string]int{}
	for _, e := range inv {
		seen := map[string]bool{}
		for _, h := range cov[e.ID] {
			if !seen[h.Kind] {
				counts[h.Kind]++
				seen[h.Kind] = true
			}
		}
	}
	fmt.Fprintf(&b, "# Screeps API coverage\n\n_Generated by `go run ./tools gen` from `api/inventory.json` and `tools/spec_*.go`. Do not edit._\n\n")
	fmt.Fprintf(&b, "Every one of the %d documented methods and properties has at least one disposition (generation fails otherwise).\n\n", len(inv))
	b.WriteString("| Disposition | Entries | Meaning |\n|---|---:|---|\n")
	meaning := map[string]string{
		"pack":   "readable in Go: a column in the shared input tables",
		"op":     "callable from Go: a command record JS executes after the tick",
		"query":  "callable from Go: asked in round N, answered in round N+1 (engine computes)",
		"native": "computed in Go from packed data, no engine call",
		"table":  "a collection or namespace exposed by a table or by the entries below it",
		"js":     "intentionally stays in JS, with the reason given",
	}
	for _, k := range []string{"pack", "op", "query", "native", "table", "js"} {
		fmt.Fprintf(&b, "| `%s` | %d | %s |\n", k, counts[k], meaning[k])
	}
	b.WriteString("\nAn entry can have several dispositions (for example a method that is both an op and has a native helper). Deprecated entries are marked †.\n\n")
	b.WriteString("| API entry | Kind | Where |\n|---|---|---|\n")
	for _, e := range inv {
		var wh []string
		for _, h := range cov[e.ID] {
			wh = append(wh, fmt.Sprintf("%s: %s", h.Kind, strings.ReplaceAll(h.Where, "|", "\\|")))
		}
		dep := ifStr(e.Deprecated, " †", "")
		fmt.Fprintf(&b, "| `%s`%s | %s | %s |\n", e.ID, dep, e.Kind, strings.Join(wh, "<br>"))
	}
	return b.String()
}

// layoutParts is everything that defines the wire layout; both sides embed its
// hash so a stale build fails fast at bind time instead of misreading memory.
func layoutParts(l layout, ops []opRec, qs []qRec) []string {
	var parts []string
	for _, kl := range l.all() {
		parts = append(parts, fmt.Sprint(kl.k.Name, kl.base, kl.stride, kl.k.Cap))
		for _, c := range kl.k.Cols {
			parts = append(parts, c.Name)
		}
	}
	for _, h := range headerCols {
		parts = append(parts, h.Name)
	}
	for _, o := range ops {
		parts = append(parts, o.s.Cls+o.s.Method+o.s.Tag+fmt.Sprint(len(o.s.Args)))
	}
	for _, q := range qs {
		parts = append(parts, "q"+q.s.Cls+q.s.Method+q.s.Tag+fmt.Sprint(len(q.s.Args)))
	}
	parts = append(parts, resourceList...)
	parts = append(parts, structureList...)
	parts = append(parts, lookList...)
	return parts
}

// colIndex is the position of a column within a kind, or -1.
func colIndex(k kindSpec, name string) int {
	for i, c := range k.Cols {
		if c.Name == name {
			return i
		}
	}
	return -1
}

var findRe = regexp.MustCompile(`^r\.find\((FIND_\w+)\)$`)

// guardFind makes a FIND_* lookup tolerate servers that lack the constant
// (a bare reference to an undefined global would throw a ReferenceError).
func guardFind(expr string) string {
	if m := findRe.FindStringSubmatch(expr); m != nil {
		return fmt.Sprintf("(typeof %s === \"undefined\" ? [] : r.find(%s))", m[1], m[1])
	}
	return expr
}

