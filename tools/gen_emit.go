func jsOut(l layout, ops []opRec, qs []qRec) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	w("\"use strict\";\n// Code generated by `go run ./tools gen`; DO NOT EDIT. Source: tools/spec_*.go.\n\n")
	w("const LAYOUT_HASH = %d;\nconst MAX_ROUNDS = %d, CMD_WORDS = %d, CMD_CAP = %d, QRY_CAP = %d, ARENA_CAP = %d, BYTES_CAP = %d, RESP_CAP = %d;\n",
		layoutHash(layoutParts(l, ops, qs)...), maxRounds, cmdWords, cmdCap, qryCap, arenaCap, bytesCap, respCap)
	w("const TERRAIN_SLOTS = %d, TERRAIN_CELL = %d, IN_LEN = %d, OUT_LEN = 8, HDR_LEN = %d;\n", terrSlots, resTerrain, l.inLen, l.hdrLen)
	w("const RESOURCE_LIST = %s;\nconst STRUCTURE_LIST = %s;\nconst BODYPART_LIST = %s;\nconst LOOK_LIST = %s;\nconst STORE_ARENA_CAP = %d;\n\n", jsArr(resourceList), jsArr(structureList), jsArr(bodyParts), jsArr(lookList), storeArena)

	w("module.exports = function (h) {\n  const { %s } = h;\n\n", strings.Join(jsHelpers, ", "))

	// header packer
	w("  function packHeader(v) {\n")
	for _, c := range headerCols {
		w("    v[%d] = %s;\n", l.hdrIndex[c.Name], c.Expr)
	}
	w("  }\n\n")

	// tables
	w("  const TABLES = [\n")
	for i, kl := range l.all() {
		k := kl.k
		find := k.Find
		if k.Name == "room" {
			find = "Object.values(Game.rooms)"
		}
		w("    { name: %q, cap: %d, base: %d, stride: %d, nIdx: %d, find: (r) => %s,\n", k.Name, k.Cap, kl.base, kl.stride, kl.nIdx, guardFind(ifEmpty(find, "[]")))
		w("      pack(o, v, b, hd) {\n")
		if k.Pre != "" {
			w("        %s\n", k.Pre)
		}
		w("        v[b] = hd;\n")
		for j, c := range k.Cols {
			w("        v[b + %d] = %s;\n", j+1, c.Expr)
		}
		w("      } }%s\n", ifStr(i < len(l.kinds), ",", ""))
	}
	w("  ];\n\n")

	// ops
	w("  const OPS = [\n")
	for _, o := range ops {
		w("    /* %d %s */ (s, a) => %s,\n", o.code, goName(o.s), jsBody(o.s, o.spec.Tpl))
	}
	w("  ];\n  const OP_NAMES = %s;\n", jsArr(opNames(ops)))
	w("  const OP_APPROACH = %s;\n\n", jsBoolArr(ops))

	w("  const QOPS = [\n")
	for _, q := range qs {
		e := jsBody(q.s, q.spec.Tpl)
		w("    /* %d %s */ (s, a) => %s,\n", q.code, goName(q.s), marshal(q.spec.Ret, e))
	}
	w("  ];\n  const QOP_NAMES = %s;\n\n", jsArr(qNames(qs)))

	w("  return { LAYOUT_HASH, MAX_ROUNDS, CMD_WORDS, CMD_CAP, QRY_CAP, ARENA_CAP, BYTES_CAP, RESP_CAP, TERRAIN_SLOTS, TERRAIN_CELL,\n")
	w("    IN_LEN, OUT_LEN, HDR_LEN, STORE_ARENA_CAP, RESOURCE_LIST, STRUCTURE_LIST, BODYPART_LIST, LOOK_LIST, packHeader, TABLES, OPS, OP_NAMES, OP_APPROACH, QOPS, QOP_NAMES };\n};\n")
	return b.String()
}

func marshal(ret, e string) string {
	switch {
	case ret == "int":
		return "[(" + e + ") | 0]"
	case ret == "bool":
		return "[(" + e + ") ? 1 : 0]"
	case ret == "handle":
		return "[HD(" + e + ")]"
	case ret == "handles":
		return "HDS(" + e + ")"
	case ret == "steps":
		return "STEPS(" + e + ")"
	case ret == "milli":
		return "[Math.round((" + e + ") * 1000)]"
	case ret == "none":
		return "((" + e + "), [])"
	case strings.HasPrefix(ret, "custom:"):
		return "MARSHAL." + ret[7:] + "(" + e + ", s, a)"
	}
	fail("gen: unknown query return kind " + ret)
	return ""
}

func opNames(ops []opRec) []string {
	r := make([]string, len(ops))
	for i, o := range ops {
		r[i] = o.s.id() + ifStr(o.s.Tag != "", "#"+o.s.Tag, "")
	}
	return r
}

func qNames(qs []qRec) []string {
	r := make([]string, len(qs))
	for i, q := range qs {
		r[i] = q.s.id() + ifStr(q.s.Tag != "", "#"+q.s.Tag, "")
	}
	return r
}

func jsBoolArr(ops []opRec) string {
	r := make([]string, len(ops))
	for i, o := range ops {
		r[i] = ifStr(o.s.Approach, "1", "0")
	}
	return "[" + strings.Join(r, ",") + "]"
}

func jsArr(s []string) string {
	q := make([]string, len(s))
	for i, v := range s {
		q[i] = fmt.Sprintf("%q", v)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

func ifStr(c bool, a, b string) string {
	if c {
		return a
	}
	return b
}

func ifEmpty(s, d string) string { return ifStr(s == "", d, s) }

