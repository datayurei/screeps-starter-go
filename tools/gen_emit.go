func goOut(l layout, ops []opRec, qs []qRec) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }

	hash := layoutHash(layoutParts(l, ops, qs)...)

	w("// Code generated by `go run ./tools gen`; DO NOT EDIT. Source: tools/spec_*.go.\n\n")
	w("package lib\n\n")
	w("// Handle identifies a game object for this tick only (index into the JS registry); -1 is none.\n")
	w("type Handle int32\n\n// Pos is x | y<<6 | roomRef<<12 (see MakePos).\ntype Pos int32\n\n")
	w("// RoomRef encodes a room name as ((rx+512)<<10)|(ry+512) over world coordinates.\ntype RoomRef int32\n\n")
	w("// Preset selects a JS-side options object (see PRESETS in js/host.js); 0 is the default.\ntype Preset int32\n\n")
	w("// Query is the id of an engine query asked in one round and answered in the next.\ntype Query int32\n\n")

	w("const (\n\tLayoutHash = %d\n\tMaxRounds = %d\n\tCmdWords = %d\n\tCmdCap = %d\n\tQryCap = %d\n\tArenaCap = %d\n\tBytesCap = %d\n\tRespCap = %d\n", hash, maxRounds, cmdWords, cmdCap, qryCap, arenaCap, bytesCap, respCap)
	w("\tTerrainSlots = %d\n\tTerrainCell = %d\n\tTerrainLen = TerrainSlots * TerrainCell\n\tStoreArenaCap = %d\n\tInLen = %d\n\tOutLen = 8\n)\n\n", terrSlots, resTerrain, storeArena, l.inLen)
	w("// Out header words.\nconst (\n\tOutNCmd = 0\n\tOutNQry = 1\n\tOutNArena = 2\n\tOutNBytes = 3\n\tOutOverflow = 4\n\tOutNAnswered = 5\n)\n\n")

	w("// Header words (scalar game state) and per-table row counts.\nconst (\n")
	for _, h := range headerCols {
		w("\tHdr%s = %d\n", camel(h.Name), l.hdrIndex[h.Name])
	}
	w("\tHdrNRoom = %d\n", l.hdrIndex["nRoom"])
	for _, k := range kinds {
		w("\tHdrN%s = %d\n", camel(k.Name), l.hdrIndex["n_"+k.Name])
	}
	w(")\n\n")

	w("// Table geometry: row i of a table starts at Base+i*Stride; word 0 is the handle.\nconst (\n")
	for _, kl := range l.all() {
		n := camel(kl.k.Name)
		w("\t%sBase = %d\n\t%sStride = %d\n\t%sCap = %d\n", n, kl.base, n, kl.stride, n, kl.k.Cap)
	}
	w(")\n\n")

	w("// Column offsets within a row (word 0 is the handle).\nconst (\n")
	for _, kl := range l.all() {
		n := camel(kl.k.Name)
		for j, cl := range kl.k.Cols {
			w("\t%sCol%s = %d\n", n, camel(cl.Name), j+1)
		}
	}
	w(")\n\n")

	w("// Resource and structure-type wire values (append-only).\nconst (\n")
	for i, r := range resourceList {
		w("\tRes%s = %d\n", camel(r), i)
	}
	for i, s := range structureList {
		w("\tSt%s = %d\n", camel(s), i+1)
	}
	for i, p := range bodyParts {
		w("\tPart%s = %d\n", camel(p), i)
	}
	for i, p := range lookList {
		w("\tLook%s = %d\n", camel(p), i)
	}
	w(")\n\n")

	w("// Op and query codes.\nconst (\n")
	for _, o := range ops {
		w("\tOp%s = %d\n", goName(o.s), o.code)
	}
	for _, q := range qs {
		w("\tQ%s = %d\n", goName(q.s), q.code)
	}
	w("\tNumOps = %d\n\tNumQueries = %d\n)\n\n", len(ops), len(qs))

	w("// Ctx is the whole shared state between JS and Go for one tick. JS fills In,\n// Terrain, Res, RespIdx and Resp; Go fills Out, Cmd, Qry, Arena and Bytes.\n")
	w("type Ctx struct {\n\tIn [InLen]int32\n\tOut [OutLen]int32\n\tCmd [CmdCap * CmdWords]int32\n\tQry [QryCap * CmdWords]int32\n")
	w("\tArena [ArenaCap]int32\n\tBytes [BytesCap]byte\n\tResp [RespCap]int32\n\tRespIdx [QryCap * 2]int32\n\tRes [CmdCap]int32\n\tTerrain [TerrainLen]byte\n\tStoreArena [StoreArenaCap]int32\n}\n\n")

	// header + table accessors
	for _, h := range headerCols {
		w("// %s reads header word %s.\nfunc (c *Ctx) %s() int32 { return c.In[Hdr%s] }\n\n", camel(h.Name), h.Name, camel(h.Name), camel(h.Name))
	}
	for _, kl := range l.all() {
		n := camel(kl.k.Name)
		w("// N%s is the number of packed %s rows.\nfunc (c *Ctx) N%s() int { return clampN(c.In[%s], %sCap) }\n\n", n, kl.k.Name, n, hdrN(kl, n), n)
		w("// %sH is row i's object handle.\nfunc (c *Ctx) %sH(i int) Handle { return Handle(c.In[%sBase+i*%sStride]) }\n\n", n, n, n, n)
		for j, cl := range kl.k.Cols {
			w("func (c *Ctx) %s%s(i int) int32 { return c.In[%sBase+i*%sStride+%d] }\n", n, camel(cl.Name), n, n, j+1)
		}
		w("\n")
	}

	// FindByID + body-part accessor depend on column positions.
	w("// FindByID returns the handle of the object whose packed id words match, or -1.\n// Object handles change every tick; ids (idA/idB/idC) are the stable identity.\nfunc (c *Ctx) FindByID(a, b, d int32) Handle {\n")
	for _, kl := range l.all() {
		if colIndex(kl.k, "idA") < 0 {
			continue
		}
		n := camel(kl.k.Name)
		w("\tfor i, n := 0, c.N%s(); i < n; i++ {\n\t\tif c.%sIdA(i) == a && c.%sIdB(i) == b && c.%sIdC(i) == d {\n\t\t\treturn c.%sH(i)\n\t\t}\n\t}\n", n, n, n, n, n)
	}
	w("\treturn -1\n}\n\n")
	bt := colIndex(kinds[0], "bt_tough")
	w("// CreepParts returns creep i's total and active (hits > 0) count of body part p (Part* constants).\nfunc (c *Ctx) CreepParts(i, p int) (total, active int32) {\n\tb := CreepBase + i*CreepStride + %d + 2*p\n\treturn c.In[b], c.In[b+1]\n}\n\n", bt+1)

	// builders
	for _, o := range ops {
		goBuilder(&b, o)
	}
	for _, q := range qs {
		goQuery(&b, q)
	}
	return b.String()
}

func hdrN(kl kindLayout, n string) string {
	if kl.k.Name == "room" {
		return "HdrNRoom"
	}
	return "HdrN" + n
}

func params(s sig, recv bool, skip int) (decl, enc []string) {
	if recv {
		decl = append(decl, "recv Handle")
	}
	for i, k := range s.Args {
		decl = append(decl, fmt.Sprintf("a%d %s", i, goType(k)))
		_ = skip
	}
	for i := 0; i < 5; i++ {
		if i < len(s.Args) {
			enc = append(enc, goEnc(s.Args[i], fmt.Sprintf("a%d", i)))
		} else {
			enc = append(enc, "0")
		}
	}
	return
}

func goBuilder(b *strings.Builder, o opRec) {
	name := goName(o.s)
	decl, enc := params(o.s, o.recv, 0)
	recv := "0"
	if o.recv {
		recv = "int32(recv)"
	}
	fmt.Fprintf(b, "// %s emits %s(%s).\nfunc (c *Ctx) %s(%s) {\n\tc.emit(Op%s, 0, %s, %s)\n}\n\n",
		name, o.s.id(), strings.Join(o.s.Args, ", "), name, strings.Join(decl, ", "), name, recv, strings.Join(enc, ", "))
	if o.s.Approach {
		d2 := append(append([]string{}, decl...), "move Preset")
		fmt.Fprintf(b, "// %sApproach is %s, then moveTo(target, preset) if the result is ERR_NOT_IN_RANGE.\nfunc (c *Ctx) %sApproach(%s) {\n\tc.emit(Op%s, 0x8000|int32(move)<<16, %s, %s)\n}\n\n",
			name, name, name, strings.Join(d2, ", "), name, recv, strings.Join(enc, ", "))
	}
}

func goQuery(b *strings.Builder, q qRec) {
	name := "Q" + goName(q.s)
	decl, enc := params(q.s, q.recv, 0)
	recv := "0"
	if q.recv {
		recv = "int32(recv)"
	}
	fmt.Fprintf(b, "// %s asks %s(%s) -> %s. Read the answer next round with Answer.\nfunc (c *Ctx) %s(%s) Query {\n\treturn c.ask(%s, %s, %s)\n}\n\n",
		name, q.s.id(), strings.Join(q.s.Args, ", "), q.spec.Ret, name, strings.Join(decl, ", "), name, recv, strings.Join(enc, ", "))
}

