// classTarget maps an API class to the wrapper kind that carries its methods,
// and the name prefix distinguishing nested classes (Spawning, Visual, Terrain).
func classTarget(cls string) (kind, prefix string, ok bool) {
	switch cls {
	case "Creep":
		return "creep", "", true
	case "PowerCreep":
		return "powercreep", "", true
	case "Flag":
		return "flag", "", true
	case "ConstructionSite":
		return "site", "", true
	case "Room":
		return "room", "", true
	case "RoomVisual":
		return "room", "Visual", true
	case "Room.Terrain":
		return "room", "Terrain", true
	case "StructureSpawn.Spawning":
		return "structure", "Spawning", true
	}
	if !strings.Contains(cls, ".") && (strings.HasPrefix(cls, "Structure") || cls == "OwnedStructure") {
		return "structure", "", true
	}
	return "", "", false
}

func goObjOut(l layout, ops []opRec, qs []qRec) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("// Code generated by `go run ./tools gen`; DO NOT EDIT. Source: tools/spec_*.go.\n\n")
	w("package lib\n\n")

	names := map[string]map[string]string{} // type -> method -> what defined it
	def := func(typ, name, what string) {
		if names[typ] == nil {
			names[typ] = map[string]string{}
		}
		if prev, dup := names[typ][name]; dup {
			fail(fmt.Sprintf("gen: method %s.%s defined twice (%s, %s)", typ, name, prev, what))
		}
		names[typ][name] = what
	}

	for _, kl := range l.all() {
		k := kl.k
		T, n := kindType[k.Name], camel(k.Name)
		has := func(col string) bool { return colIndex(k, col) >= 0 }

		w("// %s is a row of the %s table. It is only valid during the tick it was obtained.\n", T, k.Name)
		w("type %s struct {\n\tc *Ctx\n\ti int\n}\n\n", T)
		def(T, "H", "builtin")
		def(T, "Handle", "builtin")
		def(T, "Index", "builtin")
		w("// H is the object's handle, the argument actions and queries take.\nfunc (o %s) H() Handle { return o.c.%sH(o.i) }\n\n", T, n)
		w("// Handle lets the wrapper be passed wherever an Object is expected.\nfunc (o %s) Handle() Handle { return o.H() }\n\n", T)
		w("// Index is the row index in the %s table.\nfunc (o %s) Index() int { return o.i }\n\n", k.Name, T)
		w("// %s returns every packed %s row.\nfunc (c *Ctx) %s() []%s {\n\tr := make([]%s, c.N%s())\n\tfor i := range r {\n\t\tr[i] = %s{c, i}\n\t}\n\treturn r\n}\n\n",
			kindPlural[k.Name], k.Name, kindPlural[k.Name], T, T, n, T)

		for _, col := range k.Cols {
			m := camel(col.Name)
			typ := "int32"
			if handleCols[col.Name] {
				typ = "Handle"
			}
			def(T, m, "column")
			w("func (o %s) %s() %s { return %s(o.c.%s%s(o.i)) }\n", T, m, typ, typ, n, m)
		}
		w("\n")
		if has("mine") {
			def(T, "IsMine", "builtin")
			w("// IsMine reports whether you own it.\nfunc (o %s) IsMine() bool { return o.Mine() != 0 }\n\n", T)
		}
		if has("spawning") {
			def(T, "IsSpawning", "builtin")
			w("func (o %s) IsSpawning() bool { return o.Spawning() != 0 }\n\n", T)
		}
		if has("x") && has("rm") {
			def(T, "Room", "builtin")
			def(T, "Pos", "builtin")
			w("// Room is the room this object is in (check Valid: it can be outside the packed rooms).\nfunc (o %s) Room() Room { return Room{o.c, int(o.Rm())} }\n\n", T)
			w("// Pos is the object's position as a Pos (usable by pos-taking actions).\nfunc (o %s) Pos() Pos {\n\tref := RoomRef(0)\n\tif r := int(o.Rm()); r >= 0 && r < o.c.NRoom() {\n\t\tref = RoomRef(o.c.RoomRef(r))\n\t}\n\treturn MakePos(int(o.X()), int(o.Y()), ref)\n}\n\n", T)
		}
		if has("sFree") {
			for _, p := range [][2]string{{"FreeCapacity", "SFree"}, {"UsedCapacity", "SUsed"}, {"Capacity", "SCap"}, {"Energy", "SEnergy"}} {
				def(T, p[0], "store")
				w("func (o %s) %s() int32 { return o.%s() }\n", T, p[0], p[1])
			}
			def(T, "Store", "store")
			w("// Store is the original API's creep.store / structure.store view.\nfunc (o %s) Store() Store {\n\treturn Store{o.c, o.SUsed(), o.SFree(), o.SCap(), o.SEnergy(), o.SEnergyCap(), o.SEnergyFree(), o.SOff(), o.SN()}\n}\n\n", T)
			def(T, "StoreAmount", "store")
			w("// StoreAmount is Store.getUsedCapacity(resource): energy has its own column, the rest come from the store arena.\nfunc (o %s) StoreAmount(res int32) int32 {\n\tif res == ResEnergy {\n\t\treturn o.SEnergy()\n\t}\n\treturn o.c.StoreAmount(o.SOff(), o.SN(), res)\n}\n\n", T)
		}
		if k.Name == "room" {
			for _, ok := range l.kinds {
				OT := kindType[ok.k.Name]
				def(T, kindPlural[ok.k.Name], "finder")
				w("// %s returns the packed %s objects in this room (room.find for that kind).\nfunc (o Room) %s() []%s {\n\treturn Filter(o.c.%s(), func(x %s) bool { return int(x.Rm()) == o.i })\n}\n\n",
					kindPlural[ok.k.Name], ok.k.Name, kindPlural[ok.k.Name], OT, kindPlural[ok.k.Name], OT)
			}
			def(T, "Valid", "builtin")
			w("// Valid reports whether the room is one of the packed rooms.\nfunc (o Room) Valid() bool { return o.i >= 0 && o.i < o.c.NRoom() }\n\n")
		}
	}

	opWrap := func(s sig, tpl string, query bool) (typ string, ok bool) {
		kind, _, ok := classTarget(s.Cls)
		if !ok || !hasRecv(s, tpl) {
			return "", false
		}
		return kindType[kind], true
	}
	args := func(s sig) (decl, call []string) {
		for i, k := range s.Args {
			if k == "h" {
				decl = append(decl, fmt.Sprintf("a%d Object", i))
				call = append(call, fmt.Sprintf("a%d.Handle()", i))
			} else {
				decl = append(decl, fmt.Sprintf("a%d %s", i, goType(k)))
				call = append(call, fmt.Sprintf("a%d", i))
			}
		}
		return
	}
	for _, o := range ops {
		T, ok := opWrap(o.s, o.spec.Tpl, false)
		if !ok {
			continue
		}
		_, prefix, _ := classTarget(o.s.Cls)
		name := camel(prefix + "." + o.s.Method + "." + o.s.Tag)
		decl, call := args(o.s)
		def(T, name, o.s.id())
		w("// %s: %s(%s). Queued; runs after the last round.\nfunc (o %s) %s(%s) { o.c.%s(%s) }\n\n",
			name, o.s.id(), strings.Join(o.s.Args, ", "), T, name, strings.Join(decl, ", "), goName(o.s), strings.Join(append([]string{"o.H()"}, call...), ", "))
		if o.s.Approach {
			def(T, name+"Approach", o.s.id())
			w("// %sApproach is %s, then moveTo(target, move) if out of range.\nfunc (o %s) %sApproach(%s) { o.c.%sApproach(%s) }\n\n",
				name, name, T, name, strings.Join(append(append([]string{}, decl...), "move Preset"), ", "), goName(o.s), strings.Join(append(append([]string{"o.H()"}, call...), "move"), ", "))
		}
	}
	for _, q := range qs {
		T, ok := opWrap(q.s, q.spec.Tpl, true)
		if !ok {
			continue
		}
		_, prefix, _ := classTarget(q.s.Cls)
		name := "Q" + camel(prefix+"."+q.s.Method+"."+q.s.Tag)
		decl, call := args(q.s)
		def(T, name, q.s.id())
		w("// %s asks %s(%s) -> %s. Read the answer in a later round with Answer.\nfunc (o %s) %s(%s) Query { return o.c.Q%s(%s) }\n\n",
			name, q.s.id(), strings.Join(q.s.Args, ", "), q.spec.Ret, T, name, strings.Join(decl, ", "), goName(q.s), strings.Join(append([]string{"o.H()"}, call...), ", "))
	}
	return b.String()
}
